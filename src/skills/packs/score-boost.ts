/** 按 "## " 标题行切段（含标题行），返回原文段落数组。 */
function splitScoreBoostSections(template: string): string[] {
  const sections: string[] = [];
  let current: string[] | null = null;
  for (const line of template.split('\n')) {
    if (line.startsWith('## ')) {
      if (current !== null) sections.push(current.join('\n'));
      current = [line];
    } else if (current !== null) {
      current.push(line);
    }
  }
  if (current !== null) sections.push(current.join('\n'));
  return sections;
}

function pickScoreBoostSections(titlePrefixes: string[]): string {
  const matched: string[] = [];
  for (const prefix of titlePrefixes) {
    const hit = splitScoreBoostSections(SCORE_BOOST_TEMPLATE).find((s) => s.startsWith(prefix));
    if (hit !== undefined) matched.push(hit);
  }
  return matched.join('\n\n').trim();
}

