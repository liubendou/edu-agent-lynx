export function retrieveScoreBoostFragment(keywords: string[]): string {
  const sections = splitScoreBoostSections(SCORE_BOOST_TEMPLATE);
  const hitIndices = new Set<number>();
  for (const kw of keywords) {
    for (const prefix of SCORE_BOOST_RETRIEVAL_KEYWORDS[kw] ?? []) {
      const idx = sections.findIndex((s) => s.startsWith(prefix));
      if (idx >= 0) hitIndices.add(idx);
    }
  }
  return [...hitIndices].sort((a, b) => a - b).map((i) => sections[i]).join('\n\n').trim();
}
